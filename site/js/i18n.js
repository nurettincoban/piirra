export function lang() { return settings.lang === 'tr' ? 'tr' : 'en'; }

export function t(key, vars) {
  const table = S[lang()];
  let s = table[key] ?? S.en[key] ?? key;
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}

// Pick the current-language field from a { en, tr } object or a word-like item.
export function L(obj) {
  if (!obj) return '';
  return obj[lang()] ?? obj.en ?? '';
}

export function levelName(lv) { return t('lv' + lv); }
