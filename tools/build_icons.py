"""Builds site/data/lucide.js with only the Lucide icons the app uses.

Usage:
    npm pack lucide@0.460.0 && tar xzf lucide-0.460.0.tgz
    python tools/build_icons.py package/dist/esm/icons

The icon files are parsed as text; no third-party code is executed.
Every quoted string in site/js and site/data that is a Lucide icon name is included,
plus every word illustration written as 'l:<name>'.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, 'site')


def load_lucide(src):
    icons = {}
    for f in sorted(os.listdir(src)):
        if not f.endswith('.js'):
            continue
        text = open(os.path.join(src, f), encoding='utf8').read()
        m = re.search(r'defaultAttributes,\s*(\[.*\])\s*\];\s*export', text, re.S)
        if not m:
            continue
        body = re.sub(r'([{,]\s*)([A-Za-z][A-Za-z0-9-]*)\s*:', lambda x: x.group(1) + '"' + x.group(2) + '":', m.group(1))
        nodes = json.loads(body)
        icons[f[:-3]] = [[n[0], {k: v for k, v in n[1].items() if k != 'key'}] for n in nodes]
    return icons


def used_names(icons):
    names = set()
    for folder in ('js', 'data'):
        for dirpath, _, files in os.walk(os.path.join(SITE, folder)):
            for f in files:
                if not f.endswith('.js') or f == 'lucide.js':
                    continue
                text = open(os.path.join(dirpath, f), encoding='utf8').read()
                for s in re.findall(r"""['"`](?:l:)?([a-z0-9][a-z0-9-]*)['"`]""", text):
                    if s in icons:
                        names.add(s)
    return names


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    icons = load_lucide(sys.argv[1])
    names = sorted(used_names(icons))
    out = os.path.join(SITE, 'data', 'lucide.js')
    with open(out, 'w', encoding='utf8') as fh:
        fh.write('// Generated by tools/build_icons.py from Lucide Icons (ISC licence, see LUCIDE-LICENSE). Do not edit by hand.\n')
        fh.write('export const LUCIDE = {\n')
        for n in names:
            fh.write(f'  {json.dumps(n)}: {json.dumps(icons[n], separators=(",", ":"))},\n')
        fh.write('};\n')
    print(f'{len(names)} icons -> {out}')


if __name__ == '__main__':
    main()
